def detect_category_multilingual(text: str) -> str:
    """Categorizes the patient's primary concern into a clinical organ system across all 9 languages."""
    lower = text.lower()
    for cat, pattern in CATEGORY_PATTERNS.items():
        if re.search(pattern, lower):
            return cat
    return "general"


def get_turn_1(category: str, lang: str) -> Tuple[str, List[Dict[str, str]]]:
    cat_dict = TURN_1_DATA.get(category, TURN_1_DATA["general"])
    res = cat_dict.get(lang) or cat_dict.get("en")
    return res[0], res[1]


